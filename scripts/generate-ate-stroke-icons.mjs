// Regenerates ate-stroke-icons.ts from the SVGs exported by Figma.
// Usage: node scripts/generate-ate-stroke-icons.mjs <svg-folder> <output.ts>
// - one file per icon, named after the icon key (bold.svg, addRowBefore.svg…)
// - every color becomes currentColor, width/height are removed (the icon is sized in CSS with 1em)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const [
  dir = "icons/stroke",
  out = "projects/angular-tiptap-editor/src/lib/icons/ate-stroke-icons.ts",
] = process.argv.slice(2);

const clean = svg =>
  svg
    .replace(/<\?xml[^>]*>|<!--[\s\S]*?-->/g, "")
    .replace(/<svg([^>]*)\swidth="[^"]*"/, "<svg$1")
    .replace(/<svg([^>]*)\sheight="[^"]*"/, "<svg$1")
    .replace(/(fill|stroke)="(?!none|currentColor)[^"]*"/g, '$1="currentColor"')
    .replace(/<clipPath[\s\S]*?<\/clipPath>|<defs>\s*<\/defs>|\sclip-path="[^"]*"/g, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .trim();

const icons = readdirSync(dir)
  .filter(f => f.endsWith(".svg"))
  .sort()
  .map(f => [basename(f, ".svg"), clean(readFileSync(join(dir, f), "utf8"))]);

writeFileSync(
  out,
  `// Generated by scripts/generate-ate-stroke-icons.mjs, do not edit by hand.
// /ATE stroke icons: 24 grid, 2px stroke, round caps. Usage: provideAteIcons(ATE_STROKE_ICONS)
import type { AteIcons } from "../services/ate-icon-registry.service";

export const ATE_STROKE_ICONS: AteIcons = {
${icons.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n")}
};
`
);
console.log(`${icons.length} icons -> ${out}`);
